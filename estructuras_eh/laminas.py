# ------------------------------------------------------------------ red compacta (cable semiaislado + espaciador)
#   brz = brazos antibalanceo [z, x_punta];  m = cable mensajero [x, z];  tipo C = conductor en espaciador
def _comp(zb, xt, n3=False):
    k = 1.15
    xs, dz = (0.14, (0.16, 0.48, 0.75)) if n3 else (0.12, (0.16, 0.40, 0.59))
    xc = xt * k
    return ([[xc - xs, zb + dz[1], "C"], [xc + xs, zb + dz[1], "C"], [xc, zb + dz[2], "C"]], [xc, zb + dz[0]])
